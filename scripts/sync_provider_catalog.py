#!/usr/bin/env python3
"""Snapshot every Venice text model and every Phala TEE model into router config."""

from __future__ import annotations

import argparse
import asyncio
import hashlib
from pathlib import Path
from typing import Any

import httpx
import yaml

VENICE_URL = "https://api.venice.ai/api/v1/models"
PHALA_URL = "https://inference.phala.com/v1/models"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--base", default="config/models.yaml")
    parser.add_argument("--output", default="config/provider-models.yaml")
    parser.add_argument("--timeout", type=float, default=30)
    args = parser.parse_args()
    base = yaml.safe_load(Path(args.base).read_text()) or {}
    curated = set(base.get("models", {}))
    venice_response, phala_response = asyncio.run(_fetch(args.timeout))
    venice_response.raise_for_status()
    phala_response.raise_for_status()
    venice = [item for item in venice_response.json()["data"] if item.get("type") == "text"]
    phala = [item for item in phala_response.json()["data"] if item.get("is_tee") is True]
    generated: dict[str, dict[str, Any]] = {"models": {}, "endpoints": {}}
    for item in sorted(venice, key=lambda value: str(value["id"])):
        _add_venice(generated, item)
    for item in sorted(phala, key=lambda value: str(value["id"])):
        if item["id"] not in curated and item["id"] not in generated["models"]:
            _add_phala(generated, item)
    output = Path(args.output)
    output.write_text(
        "# Generated by scripts/sync_provider_catalog.py; do not edit manually.\n"
        + yaml.safe_dump(generated, sort_keys=False, allow_unicode=True, width=1000)
    )
    print(
        f"Wrote {len(venice)} Venice models and "
        f"{len(generated['models']) - len(venice)} additional Phala TEE models to {output}"
    )
    return 0


async def _fetch(request_timeout: float) -> tuple[httpx.Response, httpx.Response]:
    async with httpx.AsyncClient(timeout=request_timeout) as client:
        return await asyncio.gather(client.get(VENICE_URL), client.get(PHALA_URL))


def _endpoint_id(provider: str, model_id: str) -> str:
    digest = hashlib.sha256(model_id.encode()).hexdigest()[:12]
    return f"{provider}-catalog-{digest}"


def _capabilities(parameters: list[str]) -> list[str]:
    values = set(parameters)
    result = []
    if "tools" in values:
        result.append("tools")
    if "tool_choice" in values:
        result.append("tool_choice")
    if {"response_format", "structured_outputs"} & values:
        result.append("structured_outputs")
    if {"reasoning", "reasoning_effort", "include_reasoning"} & values:
        result.append("reasoning")
    return result


def _add_venice(output: dict[str, dict[str, Any]], item: dict[str, Any]) -> None:
    model_id = str(item["id"])
    spec = item.get("model_spec", {})
    raw_capabilities = spec.get("capabilities", {})
    capabilities = []
    if raw_capabilities.get("supportsFunctionCalling"):
        capabilities.extend(["tools", "tool_choice"])
    if raw_capabilities.get("supportsResponseSchema"):
        capabilities.append("structured_outputs")
    if raw_capabilities.get("supportsReasoning"):
        capabilities.append("reasoning")
    input_modalities = ["text"]
    if raw_capabilities.get("supportsVision"):
        input_modalities.append("image")
    pricing = spec.get("pricing", {})
    privacy = str(spec.get("privacy", "anonymized"))
    endpoint_id = _endpoint_id("venice", model_id)
    output["models"][model_id] = {
        "name": spec.get("name", model_id),
        "description": spec.get("description"),
        "owned_by": str(item.get("owned_by", "venice.ai")),
        "created": item.get("created"),
        "max_context_length": spec.get("availableContextTokens") or item.get("context_length"),
        "max_output_length": spec.get("maxCompletionTokens"),
        "capabilities": capabilities,
        "input_modalities": input_modalities,
        "traits": spec.get("traits", []),
        "provider_privacy": privacy,
    }
    output["endpoints"][endpoint_id] = {
        "model": model_id,
        "provider": "venice",
        "upstream_model": model_id,
        "priority": 100,
        "capabilities": capabilities,
        "privacy": {
            "level": "no-retention" if privacy == "private" else "standard",
            "execution": "standard",
            "retention": "zero" if privacy == "private" else "anonymized",
            "attestation": "none",
            "transport": "tls",
        },
        "pricing": {
            "input_per_million_usd": float(pricing.get("input", {}).get("usd", 0)),
            "output_per_million_usd": float(pricing.get("output", {}).get("usd", 0)),
            "cache_read_per_million_usd": float(pricing.get("cache_input", {}).get("usd", 0)),
        },
    }


def _add_phala(output: dict[str, dict[str, Any]], item: dict[str, Any]) -> None:
    model_id = str(item["id"])
    capabilities = _capabilities(item.get("supported_parameters", []))
    endpoint_id = _endpoint_id("phala", model_id)
    output["models"][model_id] = {
        "name": item.get("name", model_id),
        "description": item.get("description"),
        "owned_by": model_id.split("/", 1)[0],
        "created": item.get("created"),
        "max_context_length": item.get("context_length"),
        "max_output_length": item.get("max_output_length"),
        "capabilities": capabilities,
        "input_modalities": item.get("input_modalities", ["text"]),
        "output_modalities": item.get("output_modalities", ["text"]),
        "provider_privacy": "private",
    }
    pricing = item.get("pricing", {})
    output["endpoints"][endpoint_id] = {
        "model": model_id,
        "provider": "phala",
        "upstream_model": model_id,
        "priority": 10,
        "capabilities": capabilities,
        "privacy": {
            "level": "tee",
            "execution": "gpu-tee",
            "retention": "zero",
            "attestation": "phala-aci-receipt",
            "transport": "tee-terminated-tls",
        },
        "pricing": {
            "input_per_million_usd": float(pricing.get("prompt", 0)) * 1_000_000,
            "output_per_million_usd": float(pricing.get("completion", 0)) * 1_000_000,
            "cache_read_per_million_usd": float(pricing.get("input_cache_read", 0)) * 1_000_000,
        },
    }


if __name__ == "__main__":
    raise SystemExit(main())
